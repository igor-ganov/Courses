import { describe, expect, it } from 'vitest';
import { COURSES } from './index';
import покрытие from '~/assets/fonts/glifi.json';

/**
 * Шрифты урезаны до знаков, которые в тетради встречаются, — иначе Caveat
 * тащит сорок пять килобайт кириллицы с диакритикой и старославянскими
 * буквами ради семидесяти нужных.
 *
 * Урезание значит, что в тексте курса может однажды появиться знак, которого
 * в шрифте нет. Читатель увидит квадратик, автор — ничего: сборка пройдёт,
 * тесты пройдут, страница откроется. Поэтому проверка здесь.
 *
 * Смотрим на содержание, а не на исходники: комментарии в коде на страницу не
 * попадают, и требовать для них глифов незачем.
 */

/** Все знаки, которые курс выводит на экран. */
function znaki(): Map<number, string> {
  const где = new Map<number, string>();
  const пройти = (значение: unknown, адрес: string) => {
    if (typeof значение === 'string') {
      for (const знак of значение) {
        const c = знак.codePointAt(0)!;
        if (!где.has(c)) где.set(c, адрес);
      }
    } else if (Array.isArray(значение)) {
      значение.forEach((э, i) => пройти(э, `${адрес}[${i}]`));
    } else if (значение && typeof значение === 'object') {
      for (const [ключ, э] of Object.entries(значение)) пройти(э, `${адрес}.${ключ}`);
    }
  };
  for (const курс of COURSES) пройти(курс, курс.id);
  return где;
}

describe('шрифты покрывают содержание', () => {
  const покрыто = new Set<number>(покрытие.families['*']);

  it('каждый знак курса нарисован своим шрифтом, а не системным', () => {
    const беды: string[] = [];
    for (const [c, адрес] of znaki()) {
      /* Управляющие знаки и перевод строки шрифту не нужны. */
      if (c < 0x20) continue;
      if (!покрыто.has(c)) {
        беды.push(`«${String.fromCodePoint(c)}» U+${c.toString(16).toUpperCase()} в ${адрес}`);
      }
    }
    expect(
      беды,
      'знаки без глифа: перезапустите `node scripts/caratteri.mjs` или замените их в тексте',
    ).toEqual([]);
  });

  it('подписи приборов — тоже содержание, и тоже покрыты', () => {
    /* Дыра, найденная на галочке. Проверка выше смотрела только курс, а
       приборы печатают свои подписи сами — «отобрано», «в пустоту», знаки
       состояния. Знак «✓», поставленный в виджете, прошёл бы насквозь: в
       содержании его нет, а в шрифте нет тем более, и читатель увидел бы
       квадратик.

       Ищем в исходниках приборов знаки за пределами латиницы, кириллицы и
       обычной пунктуации: именно там водятся типографские украшения, для
       которых глифа не заказано. */
    const беды: string[] = [];
    const файлы = import.meta.glob('~/widgets/**/*.ts', { query: '?raw', import: 'default', eager: true });
    for (const [путь, текст] of Object.entries(файлы as Record<string, string>)) {
      for (const знак of текст) {
        const c = знак.codePointAt(0)!;
        if (c < 0x80) continue;
        if (c >= 0x0400 && c <= 0x04ff) continue;
        if (покрыто.has(c)) continue;
        беды.push(`«${знак}» U+${c.toString(16).toUpperCase()} в ${путь}`);
      }
    }
    expect(
      [...new Set(беды)],
      'знаки без глифа в приборах: нарисуйте их росчерком или закажите глиф',
    ).toEqual([]);
  });

  it('опись не пустая и покрывает кириллицу целиком', () => {
    expect(покрыто.size).toBeGreaterThan(150);
    /* Склонения и падежи собираются на ходу; неполный алфавит однажды даст
       квадратик в слове, которого в содержании нет ни одной строкой. */
    for (let c = 0x0410; c <= 0x044f; c += 1) expect(покрыто.has(c), String.fromCodePoint(c)).toBe(true);
    expect(покрыто.has(0x0401)).toBe(true);
    expect(покрыто.has(0x0451)).toBe(true);
  });

  it('у каждого семейства своё покрытие, и текстовое — самое полное', () => {
    /* Literata набирает основной текст: если чего-то нет в ней, знак приедет
       из накладки, и это нормально. А вот пустое семейство означает, что
       урезание съело всё. */
    for (const [семья, точки] of Object.entries(покрытие.families)) {
      expect(точки.length, семья).toBeGreaterThan(0);
    }
    expect(покрытие.families['Literata']!.length).toBeGreaterThan(180);
  });
});
