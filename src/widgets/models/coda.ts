/**
 * ОЧЕРЕДЬ И ДВЕРЬ — модель одной и той же задачи в двух обличьях.
 *
 * Задача такая: не платить за каждое событие в отдельности. Она встречается
 * в курсе дважды, и оба раза выглядит по-разному:
 *
 *   — «дверь»: тридцать контроллеров хотят знать о подах. Опрос — каждый
 *     спрашивает весь список раз в секунду, и apiserver считает объекты
 *     тысячами. Слежение — каждый получает только изменения, а читает из
 *     своей копии, не трогая дверь вовсе;
 *   — «очередь»: изменения приходят пачками, и обрабатывать каждое значит
 *     сделать сто раз то, что достаточно сделать один. Очередь хранит не
 *     события, а ключи объектов, и повторный ключ её не удлиняет.
 *
 * Это одна модель, потому что и там и там считается одно: сколько работы
 * вышло на одно и то же изменение мира. Разные обличья — разные подписи.
 *
 * Модель чистая и без экрана: её гоняют тесты, а виджет только рисует.
 */

export type Modo = 'porta' | 'coda';

export interface CodaSettings {
  readonly modo: Modo;
  /** Сколько объектов в кластере — их и приходится перечитывать при опросе. */
  readonly objects: number;
  /** Сколько наблюдателей: контроллеров при опросе, слушателей при слежении. */
  readonly watchers: number;
  /** Как часто опрашивают, секунды. Меньше — свежее и дороже. */
  readonly period: number;
  /** Дёшево ли: опрос против слежения, событие против ключа. */
  readonly cheap: boolean;
  readonly dt: number;
}

export interface CodaState {
  readonly time: number;
  /** Работы за последнюю секунду: объектов через дверь или обработок ключа. */
  readonly rate: number;
  /** Работы всего за прогон. */
  readonly total: number;
  /** Сколько изменений случилось в мире за прогон. */
  readonly changes: number;
  /** Работы на одно изменение — то самое число, ради которого всё считается. */
  readonly perChange: number;
  /** Что лежит в очереди прямо сейчас (только в обличье очереди). */
  readonly queued: number;
  /** Была ли пачка изменений только что. */
  readonly bursting: boolean;
}

export interface Coda {
  step(): CodaState;
  state(): CodaState;
  reset(): void;
  set(patch: Partial<CodaSettings>): void;
  settings(): CodaSettings;
  /** Выкатка: сто изменений одного объекта разом. */
  burst(n?: number): void;
}

export function createCoda(settings: CodaSettings): Coda {
  let cfg: CodaSettings = { ...settings };
  let time = 0;
  let работы = 0;
  let изменений = 0;
  let вОчереди = 0;
  let doОпроса = 0;
  let doОбработки = 0;
  let пачкаДо = 0;
  let заСекунду = 0;
  let секунда = 0;
  let темп = 0;

  function завести(): void {
    time = 0;
    работы = 0;
    изменений = 0;
    вОчереди = 0;
    doОпроса = cfg.period;
    doОбработки = 0;
    пачкаДо = 0;
    заСекунду = 0;
    секунда = 0;
    темп = 0;
  }

  завести();

  function снимок(): CodaState {
    return {
      time: Number(time.toFixed(2)),
      rate: Math.round(темп),
      total: Math.round(работы),
      changes: изменений,
      perChange: изменений > 0 ? Number((работы / изменений).toFixed(2)) : 0,
      queued: вОчереди,
      bursting: time < пачкаДо,
    };
  }

  function step(): CodaState {
    const dt = cfg.dt;
    time += dt;

    if (cfg.modo === 'porta') {
      /* Дверь. При опросе каждый наблюдатель раз в период тянет весь список;
         при слежении дверь платит только за само изменение — по одному
         сообщению каждому, кто следит. Изменений мало, наблюдателей много:
         поэтому опрос дороже на порядки, а не на проценты. */
      doОпроса -= dt;
      if (doОпроса <= 0) {
        doОпроса = cfg.period;
        if (cfg.cheap) {
          /* Слежение: дверь молчит, пока мир не изменился. */
        } else {
          работы += cfg.objects * cfg.watchers;
          заСекунду += cfg.objects * cfg.watchers;
        }
      }
    } else {
      /* Очередь. Обработка занимает время; за это время в очередь успевает
         набежать ещё. По ключу повторы схлопываются, по событию — нет. */
      doОбработки -= dt;
      if (doОбработки <= 0 && вОчереди > 0) {
        вОчереди -= 1;
        работы += 1;
        заСекунду += 1;
        doОбработки = 0.25;
      }
    }

    секунда += dt;
    if (секунда >= 1) {
      темп = заСекунду / секунда;
      заСекунду = 0;
      секунда = 0;
    }

    return снимок();
  }

  return {
    step,
    state: снимок,
    reset: завести,
    settings: () => cfg,
    set(patch) {
      cfg = { ...cfg, ...patch };
      /* Смена обличья или режима начинает счёт заново: сравнивать половину
         прогона при опросе с половиной при слежении нечестно. */
      if (patch.modo !== undefined || patch.cheap !== undefined) завести();
    },
    burst(n = 100) {
      изменений += n;
      пачкаДо = time + 0.6;
      if (cfg.modo === 'porta') {
        /* При слежении дверь платит за каждое изменение по одному сообщению
           каждому следящему. При опросе изменения ей вообще ничего не
           стоят — она и так перечитывает всё по расписанию. */
        if (cfg.cheap) {
          работы += n * cfg.watchers;
          заСекунду += n * cfg.watchers;
        }
        return;
      }
      /* Очередь: по событию в неё ложится каждое изменение, по ключу — один
         ключ, сколько бы изменений одного объекта ни пришло. */
      вОчереди += cfg.cheap ? (вОчереди > 0 ? 0 : 1) : n;
    },
  };
}

