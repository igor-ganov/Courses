/**
 * ГЛИФЫ — какие знаки вообще могут появиться на страницах тетради.
 *
 * Нужно затем, что шрифты урезаны до этого набора. Google отдаёт кириллический
 * Caveat весом в сорок пять килобайт на весь алфавит с диакритикой; тетради из
 * него нужно около сотни знаков, и это разница между «шрифт приезжает вместе
 * со страницей» и «текст десять раз меняет вид по дороге».
 *
 * Собирается по исходникам, а не по собранному сайту: проверка обязана
 * работать без сборки, иначе она не встанет в тесты. Исходники — это весь
 * авторский текст: содержание курсов, подписи приборов, текст страниц и
 * `content:` в стилях.
 *
 * Сверх собранного всегда добавляется обязательный набор: латиница, цифры и
 * знаки препинания приезжают в вычисленных значениях — «19.55 °», «2.77e-8», —
 * которых в исходниках нет ни одной строкой.
 */

import { readdir, readFile } from 'node:fs/promises';
import { extname, join } from 'node:path';

/** Где искать авторский текст. */
const ИСХОДНИКИ = ['src'];
const РАСШИРЕНИЯ = new Set(['.ts', '.astro', '.css']);
/** Шрифты сюда не входят — сами себя они не описывают. */
const МИМО = new Set(['node_modules', 'assets', 'fonts']);

/**
 * Обязательный набор: то, что печатается вычисленным, а не написано в тексте.
 * ASCII целиком — потому что числа, единицы и латинские сокращения собираются
 * на ходу; кириллица целиком — потому что склонения и падежи тоже.
 */
function obbligatorio() {
  const out = new Set();
  for (let c = 0x20; c <= 0x7e; c += 1) out.add(c);
  /* Кириллица: А-я, Ё, ё. Дешевле держать весь алфавит, чем однажды получить
     квадратик в слове, которого не было в исходниках. */
  for (let c = 0x0410; c <= 0x044f; c += 1) out.add(c);
  out.add(0x0401);
  out.add(0x0451);
  out.add(0x00a0); /* неразрывный пробел */
  return out;
}

async function* файлы(корень) {
  for (const запись of await readdir(корень, { withFileTypes: true })) {
    if (МИМО.has(запись.name)) continue;
    const путь = join(корень, запись.name);
    if (запись.isDirectory()) yield* файлы(путь);
    else if (РАСШИРЕНИЯ.has(extname(запись.name))) yield путь;
  }
}

/**
 * Все кодовые точки, которые могут попасть на страницу.
 *
 * @param {string} корень корень проекта
 * @returns {Promise<Set<number>>}
 */
export async function glifiUsati(корень = process.cwd()) {
  const out = obbligatorio();
  for (const где of ИСХОДНИКИ) {
    for await (const путь of файлы(join(корень, где))) {
      const текст = await readFile(путь, 'utf8');
      for (const знак of текст) {
        const c = знак.codePointAt(0);
        /* Управляющие знаки шрифту не нужны. */
        if (c >= 0x20) out.add(c);
      }
    }
  }
  return out;
}

/** Печать набора в виде, который понимает pyftsubset: U+41,U+42,… */
export const perSubset = (набор) =>
  [...набор]
    .sort((a, b) => a - b)
    .map((c) => 'U+' + c.toString(16).toUpperCase())
    .join(',');
