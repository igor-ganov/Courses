/**
 * ШРИФТЫ — урезание до тех знаков, которые в тетради встречаются.
 *
 * Запускается руками, а не при каждой сборке: ходит в сеть и просит Python.
 * Кладёт файлы в `src/assets/fonts`, описание в `src/styles/caratteri.css` и
 * опись покрытых знаков в `glifi.json`. Опись нужна тесту: он падает в тот
 * день, когда в текст курса попадёт знак, которого в урезанном шрифте нет, —
 * иначе читатель увидел бы квадратик, а никто бы не заметил.
 *
 *     node scripts/caratteri.mjs
 *
 * ── Три решения, на которых всё держится ──────────────────────────────
 *
 * 1. НАБОР ЗНАКОВ ПРОСИТСЯ У GOOGLE ЦЕЛИКОМ, А НЕ ПО ДИАПАЗОНАМ.
 *
 *    Обычная выдача Google разложена по блокам Юникода: cyrillic, latin,
 *    greek, latin-ext. Русской странице нужны сразу три из них — то есть три
 *    запроса на каждое начертание и три файла на критическом пути. Параметр
 *    `text=` отдаёт ровно перечисленные знаки одним файлом.
 *
 * 2. ФАЙЛ НА НАЧЕРТАНИЕ ДЕЛИТСЯ НЕ ПО БЛОКАМ, А ПО ЧАСТОТЕ.
 *
 *    «Всегда» — кириллица, цифры и знаки препинания: без них не обходится ни
 *    одна страница. «Иногда» — латинские буквы, греческие, математические
 *    знаки: они живут в формулах, коде и подписях, и на первом экране их
 *    обычно нет. Деление важное: у рукописного Caveat латинские буквы весят
 *    34 КБ — больше, чем вся кириллица, — и платить за них при каждой
 *    загрузке значило бы отдать треть критического пути под «PID» и «log».
 *
 * 3. ИЗ НАКЛАДНЫХ ВОЗМОЖНОСТЕЙ ОСТАВЛЕН ТОЛЬКО КЕРНИНГ.
 *
 *    calt и liga тянут за собой альтернативные начертания каждой буквы:
 *    кириллический Caveat из-за них весит 38 КБ вместо 15 при тех же 69
 *    знаках — 244 глифа вместо 94. Разницу видно, если положить две строки
 *    рядом: связки чуть плотнее. Двадцати трёх килобайт перед первым словом
 *    она не стоит.
 */

import { execFile } from 'node:child_process';
import { mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { promisify } from 'node:util';
import { glifiUsati } from './glifi.mjs';

const выполнить = promisify(execFile);

const КУДА = 'src/assets/fonts';
const СТИЛЬ = 'src/styles/caratteri.css';
const ВРЕМ = 'node_modules/.cache/caratteri';
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

/**
 * Начертания, которые тетрадь несёт.
 *
 * `цельно` — не делить на «всегда» и «иногда». Стоит у Caveat, и вот почему:
 * рукописным набраны подписи ручек вроде «усиление P», где латинская буква
 * сидит внутри русского слова. Приедь она отдельным файлом — и на первой
 * загрузке эта одна буква была бы набрана запасным шрифтом посреди
 * рукописной строки. Заметно это сильнее, чем двенадцать килобайт: у
 * Literata и PT Mono запасной шрифт того же рода, и подмена там не бросается
 * в глаза, а у рукописного бросается.
 */
const НАЧЕРТАНИЯ = [
  { имя: 'Caveat', файл: 'caveat', запрос: 'Caveat:wght@700', style: 'normal', weight: '700', цельно: true },
  { имя: 'Literata', файл: 'literata', запрос: 'Literata:opsz,wght@14,400', style: 'normal', weight: '400' },
  { имя: 'Literata', файл: 'literata-b', запрос: 'Literata:opsz,wght@14,600', style: 'normal', weight: '600' },
  {
    имя: 'Literata',
    файл: 'literata-i',
    запрос: 'Literata:ital,opsz,wght@1,14,400',
    style: 'italic',
    weight: '400',
  },
  { имя: 'PT Mono', файл: 'pt-mono', запрос: 'PT+Mono', style: 'normal', weight: '400' },
];

/** Откуда добираются знаки, которых нет ни в одном текстовом шрифте. */
const НАКЛАДКА = ['Noto+Serif:wght@400', 'Noto+Sans+Math'];

/** Буква ли это — латинская или из Latin-1. Только по ним и проходит раздел. */
const БУКВА = (c) =>
  (c >= 0x41 && c <= 0x5a) ||
  (c >= 0x61 && c <= 0x7a) ||
  (c >= 0xc0 && c <= 0xff && c !== 0xd7 && c !== 0xf7);

/** Кириллица и всё, что не буква, — то есть цифры, знаки, пробел. */
const ВСЕГДА = (c) => (c >= 0x0400 && c <= 0x04ff) || (c < 0x0370 && !БУКВА(c));

/* ── помощники ─────────────────────────────────────────────────────── */

/** Кодовые точки, которые файл шрифта на самом деле покрывает. */
async function copertura(путь) {
  const { stdout } = await выполнить('python3', [
    '-c',
    /* Урезание до набора, которого в шрифте нет, оставляет файл вовсе без
       таблицы соответствий — тогда getBestCmap отдаёт None, а не пустоту. */
    'import sys;from fontTools.ttLib import TTFont;' +
      'cm=TTFont(sys.argv[1]).getBestCmap() or {};' +
      'print(",".join(str(c) for c in sorted(cm)))',
    путь,
  ]);
  return stdout.trim() === '' ? [] : stdout.trim().split(',').map(Number);
}

/** Урезать файл под набор. Возвращает покрытие или null, если ничего не нашлось. */
async function urezat(сырой, готовый, коды) {
  await выполнить('pyftsubset', [
    сырой,
    `--unicodes=${[...коды].map((c) => 'U+' + c.toString(16)).join(',')}`,
    '--flavor=woff2',
    '--output-file=' + готовый,
    '--layout-features=kern,ccmp,mark,mkmk',
    '--no-hinting',
    '--desubroutinize',
    '--name-IDs=',
    '--drop-tables+=DSIG',
  ]);
  const покрыто = (await copertura(готовый)).filter((c) => коды.has(c));
  if (покрыто.length === 0) {
    await rm(готовый);
    return null;
  }
  return покрыто;
}

/** Список кодовых точек в виде диапазонов: U+41-5A, U+61-7A, … */
function intervalli(коды) {
  const с = [...коды].sort((a, b) => a - b);
  const части = [];
  const в = (c) => 'U+' + c.toString(16).toUpperCase();
  for (let i = 0; i < с.length; ) {
    let j = i;
    while (j + 1 < с.length && с[j + 1] === с[j] + 1) j += 1;
    части.push(i === j ? в(с[i]) : `${в(с[i])}-${с[j].toString(16).toUpperCase()}`);
    i = j + 1;
  }
  return части.join(', ');
}

/**
 * Скачать у Google начертание, урезанное под перечисленные знаки.
 *
 * Возвращает путь к сырому файлу или null: у шрифта может не оказаться ни
 * одного из этих знаков, и тогда Google не отдаёт ничего.
 */
async function scarica(запрос, style, коды, куда) {
  if (коды.size === 0) return null;
  const текст = encodeURIComponent([...коды].map((c) => String.fromCodePoint(c)).join(''));
  const css = await (
    await fetch(`https://fonts.googleapis.com/css2?family=${запрос}&text=${текст}`, {
      headers: { 'User-Agent': UA },
    })
  ).text();
  /* У курсива и прямого один запрос отдаёт оба начертания. */
  for (const блок of css.split('@font-face').slice(1)) {
    if ((/font-style:\s*(\w+)/.exec(блок)?.[1] ?? 'normal') !== style) continue;
    const src = /src:\s*url\(([^)]+)\)/.exec(блок)?.[1];
    if (!src) continue;
    await writeFile(куда, Buffer.from(await (await fetch(src)).arrayBuffer()));
    return куда;
  }
  return null;
}

/* ── сборка ────────────────────────────────────────────────────────── */

const глифы = await glifiUsati();
const всегда = new Set([...глифы].filter(ВСЕГДА));
const иногда = new Set([...глифы].filter((c) => !ВСЕГДА(c)));
console.log(`шрифты: знаков ${глифы.size} — всегда ${всегда.size}, иногда ${иногда.size}`);

await rm(КУДА, { recursive: true, force: true });
await mkdir(КУДА, { recursive: true });
await mkdir(ВРЕМ, { recursive: true });

const описание = [];
let было = 0;
let стало = 0;

for (const н of НАЧЕРТАНИЯ) {
  const части = н.цельно
    ? [{ имя: 'sempre', коды: глифы }]
    : [
        { имя: 'sempre', коды: всегда },
        { имя: 'raro', коды: иногда },
      ];
  for (const часть of части) {
    const сырой = join(ВРЕМ, `${н.файл}-${часть.имя}.woff2`);
    if (!(await scarica(н.запрос, н.style, часть.коды, сырой))) continue;
    было += (await stat(сырой)).size;

    const имяФайла = `${н.файл}-${часть.имя}.woff2`;
    const покрыто = await urezat(сырой, join(КУДА, имяФайла), часть.коды);
    if (!покрыто) {
      console.log(`  ${имяФайла}: ни одного нужного знака, выброшен`);
      continue;
    }
    const после = (await stat(join(КУДА, имяФайла))).size;
    стало += после;
    console.log(`  ${имяФайла}: ${(после / 1024).toFixed(1)} КБ, знаков ${покрыто.length}`);
    описание.push({ ...н, range: intervalli(покрыто), файлИмя: имяФайла, покрыто });
  }
}

/* ── накладка ──────────────────────────────────────────────────────────
   Стрелки, ≈, ≤, ∫, ∞ и подстрочные цифры в Literata просто отсутствуют —
   их нет и в исходных наборах Google. До сих пор они рисовались чужим
   шрифтом прямо посреди формулы, набранной своим, и это было заметно.
   Noto Serif близок к Literata по рисунку и закрывает подстрочные знаки;
   стрелки и знаки отношения берутся из Noto Sans Math, где они нарисованы
   математическими, а не значками. */

const текстовые = new Set(описание.flatMap((о) => о.покрыто));
const осталось = new Set([...глифы].filter((c) => !текстовые.has(c)));

if (осталось.size > 0) {
  console.log(`накладка: знаков без шрифта ${осталось.size}`);
  let n = 0;
  for (const источник of НАКЛАДКА) {
    if (осталось.size === 0) break;
    const сырой = join(ВРЕМ, `simboli-${n}.woff2`);
    if (!(await scarica(источник, 'normal', осталось, сырой))) continue;
    было += (await stat(сырой)).size;
    const имяФайла = `simboli-${n}.woff2`;
    const покрыто = await urezat(сырой, join(КУДА, имяФайла), осталось);
    if (!покрыто) continue;
    const после = (await stat(join(КУДА, имяФайла))).size;
    стало += после;
    for (const c of покрыто) осталось.delete(c);
    console.log(`  ${имяФайла}: ${(после / 1024).toFixed(1)} КБ, знаков ${покрыто.length}`);
    описание.push({
      имя: 'Simboli',
      файл: 'simboli',
      style: 'normal',
      weight: '400',
      range: intervalli(покрыто),
      файлИмя: имяФайла,
      покрыто,
    });
    n += 1;
  }
  if (осталось.size > 0) {
    console.log(
      '  без шрифта остались: ' +
        [...осталось].map((c) => String.fromCodePoint(c) + ' U+' + c.toString(16).toUpperCase()).join(' '),
    );
  }
}

/* ── описание ──────────────────────────────────────────────────────── */

/* Накладка объявляется первой: при равном весе и стиле побеждает то
   начертание, что раньше, — а перебивать текстовые ей нечем, её диапазон
   и так сведён к недостающим знакам. */
const порядок = [...описание].sort((a, b) => Number(b.имя === 'Simboli') - Number(a.имя === 'Simboli'));

await writeFile(
  СТИЛЬ,
  '/* Собран автоматически: node scripts/caratteri.mjs. Править здесь нечего.\n' +
    '\n' +
    '   Знаки урезаны до тех, что в тетради встречаются; какие именно —\n' +
    '   в assets/fonts/glifi.json, и за этим следит тест. Файлы `-sempre`\n' +
    '   несут кириллицу с цифрами и нужны всегда, `-raro` — латинские буквы,\n' +
    '   греческие и математические знаки, и приезжают, только если такой знак\n' +
    '   на странице встретился.\n' +
    '\n' +
    '   font-display у двух половин разный, и это решение.\n' +
    '\n' +
    '   `-sempre` — optional: они предзагружаются, укладываются в отведённые\n' +
    '   сто миллисекунд и рисуют текст сразу собой. Если сеть совсем плоха и\n' +
    '   не уложились — страница целиком набирается запасным шрифтом и уже не\n' +
    '   меняется. При swap вместо этого каждый файл, приехав, подменял бы\n' +
    '   шрифт под уже прочитанным текстом: десяток начертаний — десяток\n' +
    '   подмен подряд, ровно то, на что жалуются.\n' +
    '\n' +
    '   `-raro` — swap, и по обратной причине. Это единичные знаки: «P» в\n' +
    '   подписи ручки, λ в формуле. При optional они остались бы запасным\n' +
    '   шрифтом до конца загрузки — то есть латинская буква посреди\n' +
    '   рукописного слова была бы набрана не рукописным. Лучше поздно, но\n' +
    '   своим: подменяется несколько знаков, и строка от этого не едет —\n' +
    '   за этим следит e2e/stabilita.spec.ts.\n' +
    '\n' +
    '   Со второй страницы всё уже лежит на устройстве (кладёт служитель), и\n' +
    '   обе половины рисуют собой с первого кадра. */\n' +
    порядок
      .map(
        (о) =>
          `@font-face{font-family:'${о.имя}';font-style:${о.style};font-weight:${о.weight};` +
          `font-display:${о.файлИмя.endsWith('-sempre.woff2') ? 'optional' : 'swap'};` +
          `src:url('../assets/fonts/${о.файлИмя}') format('woff2');` +
          `unicode-range:${о.range}}`,
      )
      .join('\n') +
    '\n',
  'utf8',
);

/* Опись — то, что в файлах ЕСТЬ, а не то, что просили: pyftsubset кладёт
   только найденное, и опись из пожеланий врала бы там, где нужна правда. */
const покрытие = {};
for (const о of описание) {
  покрытие[о.имя] = [...new Set([...(покрытие[о.имя] ?? []), ...о.покрыто])].sort((a, b) => a - b);
}
покрытие['*'] = [...new Set(Object.values(покрытие).flat())].sort((a, b) => a - b);

await writeFile(
  join(КУДА, 'glifi.json'),
  JSON.stringify(
    {
      note:
        'Кодовые точки, которые урезанные шрифты действительно покрывают. ' +
        'Собрано scripts/caratteri.mjs из готовых файлов, а не из списка пожеланий.',
      families: покрытие,
    },
    null,
    1,
  ),
  'utf8',
);

const файлов = (await readdir(КУДА)).filter((f) => f.endsWith('.woff2')).length;
console.log(
  `шрифты: ${файлов} файлов, ${(было / 1024).toFixed(0)} → ${(стало / 1024).toFixed(0)} КБ; ` +
    `на критическом пути ${описание.filter((о) => о.файлИмя.endsWith('-sempre.woff2')).length}`,
);
