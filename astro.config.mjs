// @ts-check
import { defineConfig } from 'astro/config';

/**
 * Платформа офлайн-первая, поэтому сборка статическая: ни одного обращения к
 * сети во время работы.
 *
 * Интеграции `@astrojs/lit` здесь нет, и это решение, а не упущение. Она
 * рисует Lit-элемент на сервере и подкладывает в голову каждой страницы шим
 * для `declarative shadow DOM` — полтора килобайта блокирующего скрипта,
 * который платится за приборы даже на титульной, где их нет. Приборы этой
 * тетради ничего не показывают до первого кадра расчёта, отрисовывать их
 * заранее нечего, и включаются они собственным наблюдателем по пересечению.
 * Поэтому они здесь — просто пользовательские элементы, а не острова Astro.
 *
 * base нужен из-за GitHub Pages: сайт живёт в подкаталоге /Courses/.
 */
export default defineConfig({
  site: 'https://igor-ganov.github.io',
  base: process.env.PAGES_BASE ?? '/',
  output: 'static',
  build: { inlineStylesheets: 'auto' },
  vite: {
    resolve: {
      alias: { '~': new URL('./src', import.meta.url).pathname },
    },
    build: {
      /* Ничего не вшивать в стиль строкой base64.

         Умолчание Vite — вшивать всё мельче четырёх килобайт, и под него
         попадали мелкие куски шрифтов: греческий, латинское расширение,
         накладка со стрелками. Они нужны далеко не на всякой странице, а
         платит за них каждая: стиль блокирует отрисовку, и лишние килобайты
         в нём — это лишние килобайты перед первым словом. Отдельными файлами
         они приезжают только там, где встретились. */
      assetsInlineLimit: 0,
    },
  },
});
