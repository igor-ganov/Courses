/* ── лист и модель ───────────────────────────────────────────────────── */

const Ш = 200; // мм, ширина страницы
const В = 150; // мм, высота
const Δ = 3.2; // мм, глубина под пальцем — одна и та же везде
const СЕКТОР = (139 * Math.PI) / 180;
const УВЕЛ = 60; // смещение печати увеличено, иначе доли пикселя

const hash = (v) => {
  const t = Math.sin(v * 127.1) * 43758.5453;
  return t - Math.floor(t);
};

/* Расстояние от точки до границы листа по направлению θ. */
const доКрая = (x, y, θ) => {
  const cx = Math.cos(θ);
  const cy = Math.sin(θ);
  let t = Infinity;
  if (cx > 1e-6) t = Math.min(t, (Ш - x) / cx);
  if (cx < -1e-6) t = Math.min(t, -x / cx);
  if (cy > 1e-6) t = Math.min(t, (В - y) / cy);
  if (cy < -1e-6) t = Math.min(t, -y / cy);
  return t;
};

/* Расстояние до ближайшего закреплённого края и направление к нему. */
const доЗажима = (x, y, зажим) => {
  const свечи = [
    ['слева', x, Math.PI],
    ['справа', Ш - x, 0],
    ['сверху', y, -Math.PI / 2],
    ['снизу', В - y, Math.PI / 2],
  ].filter(([имя]) => зажим.includes(имя));
  if (!свечи.length) return [Math.min(Ш, В) / 2, 0];
  return свечи.reduce((a, b) => (a[1] <= b[1] ? a : b)).slice(1);
};

/* Куда лист уходит: туда, где ему есть куда уйти. Каждый свободный край
   тянет к себе тем сильнее, чем он ближе (вес 1/d²), и направления
   складываются — поэтому у одинокого края сектор смотрит на него, а в углу
   сам собой ложится по биссектрисе. Если тяга взаимно гасится (лист держат
   с двух сторон) — берём просто ближайший свободный край. */
const кСвободе = (x, y, зажим) => {
  const свечи = [
    ['слева', Math.max(x, 1), Math.PI],
    ['справа', Math.max(Ш - x, 1), 0],
    ['сверху', Math.max(y, 1), -Math.PI / 2],
    ['снизу', Math.max(В - y, 1), Math.PI / 2],
  ].filter(([имя]) => !зажим.includes(имя));
  if (!свечи.length) return Math.PI / 2;
  let sx = 0;
  let sy = 0;
  for (const [, d, θ] of свечи) {
    sx += Math.cos(θ) / (d * d);
    sy += Math.sin(θ) / (d * d);
  }
  const тяга = Math.hypot(sx, sy);
  const слабейшая = 1 / (Math.max(Ш, В) ** 2);
  if (тяга < слабейшая) return свечи.reduce((a, b) => (a[1] <= b[1] ? a : b))[2];
  return Math.atan2(sy, sx);
};

/* Всё нажатие целиком: масштаб, разворот сектора, наклон генератрис. */
const нажатие = (x, y, зажим) => {
  const [R] = доЗажима(x, y, зажим);
  const ось = кСвободе(x, y, зажим);
  const ψ0 = Δ / Math.max(R, 12);
  const ψ = (θ) => {
    let a = θ - ось;
    while (a > Math.PI) a -= 2 * Math.PI;
    while (a < -Math.PI) a += 2 * Math.PI;
    if (Math.abs(a) > СЕКТОР / 2) return ψ0;
    return ψ0 * (1 + 1.15 * Math.cos((Math.PI * a) / СЕКТОР) ** 2);
  };
  return { R, ось, ψ0, ψ, φ: (θ) => Math.atan(ψ(θ)) };
};

/* ── рисовалка ───────────────────────────────────────────────────────── */

const n = (v) => (Math.round(v * 100) / 100).toString();
const P = (pts) => pts.map(([a, b], i) => `${i ? 'L' : 'M'}${n(a)} ${n(b)}`).join('');

const текст = (x, y, s, cls = 'подпись', anchor = 'middle') =>
  `<text x="${n(x)}" y="${n(y)}" text-anchor="${anchor}" class="${cls}">${s}</text>`;

/* Строки текста на листе; place переводит миллиметры в точки картинки. */
const строки = (place, cls, кегль) => {
  const вон = [];
  let ряд = 0;
  for (let y = 16; y <= В - 14; y += 11) {
    let x = 14;
    let слово = 0;
    const конец = Ш - 14 - (ряд % 5 === 4 ? (Ш - 28) * 0.38 : 0);
    while (x < конец) {
      const дл = 6 + Math.floor(hash(ряд * 13.7 + слово * 3.1) * 13);
      слово += 1;
      const w = Math.min(дл, конец - x);
      if (w > 3) {
        const шт = [];
        for (let t = 0; t <= 8; t++) шт.push(place(x + (w * t) / 8, y));
        вон.push(`<path d="${P(шт)}" class="${cls}" stroke-width="${кегль}"/>`);
      }
      x += дл + 5;
    }
    ряд += 1;
  }
  return вон.join('');
};

/* ── одна карточка ───────────────────────────────────────────────────── */

function карточка({ имя, точка: [tx, ty], зажим, вывод }) {
  const S = 1.28; // px на мм
  const поле = 16;
  const px = (x, y) => [поле + x * S, поле + y * S];
  const N = нажатие(tx, ty, зажим);

  /* Смещение печати: точка остаётся на том же расстоянии от вершины, но
     вдоль наклонённой генератрисы, поэтому её проекция ближе. На
     закреплённой границе смещение гасится — там лист держат. */
  const сдвинуть = (x, y) => {
    const dx = x - tx;
    const dy = y - ty;
    const s = Math.hypot(dx, dy);
    if (s < 0.4) return px(x, y);
    const θ = Math.atan2(dy, dx);
    const держат = зажим.length ? Math.max(0, 1 - s / Math.max(доКрая(tx, ty, θ), 1)) : 1;
    const k = (Math.cos(N.φ(θ)) - 1) * УВЕЛ * держат;
    return px(x + dx * k, y + dy * k);
  };

  /* Сектор отрыва — до самой границы листа. */
  const сектор = [[поле + tx * S, поле + ty * S]];
  for (let t = 0; t <= 30; t++) {
    const θ = N.ось - СЕКТОР / 2 + (t / 30) * СЕКТОР;
    const L = доКрая(tx, ty, θ);
    сектор.push(px(tx + Math.cos(θ) * L, ty + Math.sin(θ) * L));
  }

  const рёбра = [-1, 1].map((зн) => {
    const θ = N.ось + (зн * СЕКТОР) / 2;
    const L = доКрая(tx, ty, θ);
    return `<path d="${P([px(tx, ty), px(tx + Math.cos(θ) * L, ty + Math.sin(θ) * L)])}" class="ребро"/>`;
  });

  const лучи = [];
  for (let k = 0; k < 28; k++) {
    const θ = (k / 28) * Math.PI * 2;
    const L = доКрая(tx, ty, θ);
    лучи.push(`<path d="${P([px(tx, ty), px(tx + Math.cos(θ) * L, ty + Math.sin(θ) * L)])}" class="генератриса"/>`);
  }

  const края = [
    ['слева', [0, 0], [0, В]],
    ['справа', [Ш, 0], [Ш, В]],
    ['сверху', [0, 0], [Ш, 0]],
    ['снизу', [0, В], [Ш, В]],
  ]
    .map(([имя, a, b]) => {
      const [x1, y1] = px(...a);
      const [x2, y2] = px(...b);
      return `<line x1="${n(x1)}" y1="${n(y1)}" x2="${n(x2)}" y2="${n(y2)}" class="${зажим.includes(имя) ? 'зажат' : 'свободен'}"/>`;
    })
    .join('');

  const [fx, fy] = px(tx, ty);
  const [rx, ry] = px(
    tx + Math.cos(N.ось) * Math.min(доКрая(tx, ty, N.ось), 46),
    ty + Math.sin(N.ось) * Math.min(доКрая(tx, ty, N.ось), 46),
  );

  return `<figure class="карточка">
  <svg viewBox="0 0 ${n(Ш * S + поле * 2)} ${n(В * S + поле * 2)}" role="img" aria-label="${имя}: страница, палец в указанном месте, сектор отрыва развёрнут к свободному краю, строки съезжают к точке касания">
    ${лучи.join('')}
    <path d="${P(сектор)}Z" class="отрыв"/>
    ${строки((x, y) => px(x, y), 'печать-призрак', 1.5)}
    ${строки(сдвинуть, 'печать', 1.5)}
    ${рёбра.join('')}
    ${края}
    <line x1="${n(fx)}" y1="${n(fy)}" x2="${n(rx)}" y2="${n(ry)}" class="ось" marker-end="url(#ось)"/>
    <circle cx="${n(fx)}" cy="${n(fy)}" r="7" class="палец-круг"/>
    <circle cx="${n(fx)}" cy="${n(fy)}" r="2.4" class="палец-точка"/>
  </svg>
  <figcaption><b>${имя}</b>${вывод} <span class="цифры">R = ${Math.round(N.R)} мм · наклон ${(
    (N.φ(N.ось) * 180) / Math.PI
  ).toFixed(1)}°</span></figcaption>
</figure>`;
}

