/* Прикосновения в разных местах страницы.
 *
 * Продолжение geometria.mjs той же моделью: бумага нерастяжима, поэтому под
 * пальцем она складывается в развёртывающийся конус z(ρ,θ) = ρ·ψ(θ) —
 * прямые лучи из точки касания, вся кривизна поперёк лучей, сектор отрыва
 * ≈139°, на его границах кривизна меняет знак.
 *
 * Здесь показано то, чем нажатия отличаются друг от друга: край листа.
 * Энергия изгиба логарифмическая, деформация доходит до границ, поэтому
 * форму задают они:
 *
 *   — расстояние до ближайшего закреплённого края даёт масштаб R.
 *     Глубина под пальцем та же, значит ψ0 = Δ/R: у края конус круче и
 *     теснее, посреди листа — шире и площе;
 *   — сектор отрыва разворачивается к ближайшему свободному краю: лист
 *     уходит туда, где ему есть куда уйти;
 *   — смещение печати гаснет на закреплённой границе, потому что там лист
 *     держат.
 *
 * Правило «сектор смотрит на свободный край» — схематизация: точная задача
 * решается численно и для каждой формы листа отдельно. Всё остальное здесь
 * — прямая геометрия конуса.
 *
 *   node design/tocchi.mjs
 */

