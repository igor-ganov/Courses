/* ── модель ──────────────────────────────────────────────────────────── */

const R = 62; // мм, радиус опоры (там, где лист держат)
const Δ = 3.2; // мм, глубина вершины под пальцем
const СЕКТОР = (139 * Math.PI) / 180; // сектор отрыва
const ТОЛЩИНА = 0.1; // мм
const ЯДРО = Math.cbrt(ТОЛЩИНА) * Math.cbrt(R * R); // ≈7 мм

/* Приведённая высота ψ(θ): в секторе контакта лист приходит на опору,
   в секторе отрыва поднимается над ней. */
const ψ0 = Δ / R;
const ψ = (θ) => {
  const a = Math.atan2(Math.sin(θ), Math.cos(θ)); // в (−π, π]
  if (Math.abs(a) > СЕКТОР / 2) return ψ0;
  return ψ0 * (1 + 1.15 * Math.cos((Math.PI * a) / СЕКТОР) ** 2);
};

/* Высота листа над плоскостью опоры: конус с вершиной на глубине Δ. */
const z = (x, y) => {
  const ρ = Math.hypot(x, y);
  return -Δ + ρ * ψ(Math.atan2(y, x));
};

/* Наклон генератрисы: он один и тот же вдоль всего луча. */
const φ = (θ) => Math.atan(ψ(θ));

/* ── рисовалка ───────────────────────────────────────────────────────── */

const n = (v) => (Math.round(v * 100) / 100).toString();
const P = (pts) => pts.map(([x, y], i) => `${i ? 'L' : 'M'}${n(x)} ${n(y)}`).join('');

const hash = (v) => {
  const t = Math.sin(v * 127.1) * 43758.5453;
  return t - Math.floor(t);
};

const стрелки = `<defs>
    <marker id="pa" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse">
      <path d="M0 1L10 5L0 9z" fill="var(--акцент)"/>
    </marker>
    <marker id="pc" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">
      <path d="M0 1L10 5L0 9z" fill="var(--построение)"/>
    </marker>
  </defs>`;

const текст = (x, y, s, opts = {}) =>
  `<text x="${n(x)}" y="${n(y)}" text-anchor="${opts.anchor ?? 'middle'}" class="${opts.cls ?? 'подпись'}">${s}</text>`;

const размер = (x1, y1, x2, y2, s) =>
  `<line x1="${n(x1)}" y1="${n(y1)}" x2="${n(x2)}" y2="${n(y2)}" class="строит" marker-start="url(#pc)" marker-end="url(#pc)"/>` +
  текст((x1 + x2) / 2, (y1 + y2) / 2 - 5, s, { cls: 'число' });

/* Палец в разрезе. Точка (cx, cy) — место касания. */
const палец = (cx, cy, r, { угол = -17, сплющен = 1 } = {}) => {
  const a = сплющен * r * 0.72;
  const тело =
    `M${n(-r)} ${n(-r * 5.4)}L${n(-r * 1.02)} ${n(-r * 0.55)}` +
    `A${n(r)} ${n(r)} 0 0 0 ${n(-a)} ${n(r * 0.45)}L${n(a)} ${n(r * 0.45)}` +
    `A${n(r)} ${n(r)} 0 0 0 ${n(r * 1.02)} ${n(-r * 0.55)}L${n(r)} ${n(-r * 5.4)}`;
  const ноготь =
    `M${n(-r * 0.6)} ${n(-r * 3.2)}L${n(-r * 0.68)} ${n(-r * 1.8)}` +
    `Q0 ${n(-r * 1.32)} ${n(r * 0.68)} ${n(-r * 1.8)}L${n(r * 0.6)} ${n(-r * 3.2)}`;
  return (
    `<g transform="translate(${n(cx)} ${n(cy - r)}) rotate(${угол}) translate(0 ${n(r * 0.55)})">` +
    `<path d="${тело}" class="палец"/><path d="${ноготь}" class="строит"/></g>`
  );
};

/* Текст на бумаге: не буквы, а их место — штрихи слов по строкам. */
const текстНаЛисте = (place, { слева, справа, сверху, снизу, шагСтрок = 13, кегль = 2.2, cls = 'печать' }) => {
  const вон = [];
  let ряд = 0;
  for (let y = сверху; y <= снизу; y += шагСтрок) {
    let x = слева;
    let слово = 0;
    const конец = справа - (ряд % 4 === 3 ? (справа - слева) * 0.4 : 0);
    while (x < конец) {
      const дл = 5 + Math.floor(hash(ряд * 13.7 + слово * 3.1) * 11);
      слово += 1;
      const w = Math.min(дл, конец - x);
      if (w > 2.5) {
        const шт = [];
        for (let t = 0; t <= 8; t++) шт.push(place(x + (w * t) / 8, y));
        вон.push(`<path d="${P(шт)}" class="${cls}" stroke-width="${n(кегль)}"/>`);
      }
      x += дл + 4.5;
    }
    ряд += 1;
  }
  return вон.join('');
};

