/* Десять схем: бумага с текстом и палец, который в неё тычет.
 *
 * Модель здесь не выдуманная, а из литературы по тонким упругим листам.
 * Бумага нерастяжима: растянуть её стоит на пять-шесть порядков дороже, чем
 * согнуть, поэтому она деформируется изгибом, а изгиб по теореме Гаусса
 * сохраняет гауссову кривизну. Плоский лист имеет K = 0, значит и после
 * нажатия K = 0 всюду: чаши, ямки, купола бумага не делает — для них нужна
 * положительная кривизна, то есть растяжение.
 *
 * Вместо ямки получается развёртывающийся конус (d-cone). В цилиндрических
 * координатах с вершиной в точке нажатия
 *
 *     z(ρ, θ) = ρ · ψ(θ)
 *
 * — то есть вдоль каждого луча из точки касания лист ПРЯМОЙ, а вся кривизна
 * азимутальная и падает как 1/ρ. Часть листа при этом отходит от опоры:
 * сектор отрыва — универсальные ≈139°, не зависящие ни от силы нажатия, ни от
 * толщины, ни от материала. На границах сектора кривизна меняет знак — это
 * линии перегиба.
 *
 * Точным конусом это быть не может: в вершине кривизна 1/ρ расходится.
 * Поэтому у вершины есть ядро («кресцент»), где бумага всё-таки тянется,
 * радиусом R_c ~ h^(1/3)·R^(2/3). Для писчей бумаги 0,1 мм и опоры 60 мм это
 * около 7 мм — размером с подушечку пальца.
 *
 * Энергия изгиба логарифмическая, ln(R/R_c): деформация не локальная, она
 * доходит до краёв листа, и граничные условия задают ψ(θ).
 *
 * Источники — в подвале страницы.
 *
 *   node design/geometria.mjs
 */

